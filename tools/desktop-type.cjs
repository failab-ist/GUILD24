// Desktop type scale (User 2026-10-23: 데스크에서 글씨가 작다 - 폰과 분리해 데스크탑용 폰트 위계를 세운다).
//
// The phone stays exactly as authored. For a desktop viewport (min-width:1024px) this tool derives a second type scale
// from the sheet itself and appends it between the DESKTOP-TYPE markers at the end of dist/ui/director-review.css, the sheet that loads after
// ui.css (so it wins on equal specificity) and is read together with it:
//   - every px font size is lifted one rung on a fixed ladder (LADDER below), so the order between a caption, a body
//     line, an item name and a heading is kept and nothing reads smaller than a caption floor;
//   - a px line-height written next to a size is scaled by the same ratio;
//   - the rule keeps its own selector and its own media condition (anded with the desktop one), so the cascade between
//     rules is the one the sheet already has;
//   - sizes written through the --t-* tokens move with the tokens (redefined for desktop in the block's head).
// Run: node tools/desktop-type.cjs   (rewrites the block in place; running it twice changes nothing)
const fs=require('node:fs'),path=require('node:path');
const BASE=path.join(__dirname,'..','dist','ui','ui.css');
const FILE=path.join(__dirname,'..','dist','ui','director-review.css');
const BEGIN='/* DESKTOP-TYPE:BEGIN (generated by tools/desktop-type.cjs - edit the ladder there, not this block) */';
const END='/* DESKTOP-TYPE:END */';

// px on the sheet -> px on a desktop. Captions (10-11) land on 13, the body on 15-16, headings keep their distance.
const LADDER={8:11,9:12,10:13,11:13,12:14,13:15,13.5:15.5,14:16,14.5:16.5,15:17,16:18,17:19,18:20,19:21,20:22,21:23,22:24,23:25,24:26,25:27,26:28};
const TOKENS='--t-xs:14px;--t-sm:15px;--t-md:17px;--t-lg:20px;--t-xl:24px;--t-2xl:30px;--t-3xl:40px;';

function strip(src){const a=src.indexOf(BEGIN);if(a<0)return src;const b=src.indexOf(END,a);return src.slice(0,a).replace(/\s+$/,'')+'\n'+src.slice(b+END.length).replace(/^\s*\n/,'');}

// minimal CSS reader: top-level rules and one or more levels of @media
function parse(src){let i=0;
 function skipWs(){for(;;){while(i<src.length&&/\s/.test(src[i]))i++;if(src.startsWith('/*',i)){const e=src.indexOf('*/',i+2);i=e<0?src.length:e+2;}else break;}}
 function block(){const out=[];for(;;){skipWs();if(i>=src.length||src[i]==='}'){return out;}
  let start=i,depth=0;
  while(i<src.length&&src[i]!=='{'&&src[i]!==';'){if(src.startsWith('/*',i)){const e=src.indexOf('*/',i+2);i=e+2;continue;}if(src[i]==='"'||src[i]==="'"){const q=src[i++];while(src[i]!==q)i++;}i++;}
  const head=src.slice(start,i).replace(/\/\*[\s\S]*?\*\//g,'').trim();
  if(src[i]===';'){i++;out.push({type:'stmt',head});continue;}
  i++;
  if(head.startsWith('@media')||head.startsWith('@supports')){const kids=block();i++;out.push({type:'at',head,kids});}
  else if(head.startsWith('@')){let d=1;const s=i;while(d){if(src.startsWith('/*',i)){i=src.indexOf('*/',i+2)+2;continue;}if(src[i]==='{')d++;else if(src[i]==='}')d--;i++;}out.push({type:'rawat',head,body:src.slice(s,i-1)});}
  else{const s=i;while(src[i]!=='}'){if(src.startsWith('/*',i)){i=src.indexOf('*/',i+2)+2;continue;}if(src[i]==='"'||src[i]==="'"){const q=src[i++];while(src[i]!==q)i++;}if(src[i]==='('){let d=1;i++;while(d){if(src[i]==='(')d++;else if(src[i]===')')d--;i++;}continue;}i++;}
   out.push({type:'rule',sel:head,body:src.slice(s,i)});i++;}
 }}
 return block();}

function lift(body){// returns the declarations that change, or ''
 const decls=[];let ratio=0;
 const sizeOf=px=>{const v=parseFloat(px);const to=LADDER[v];return to===undefined?null:to;};
 // font shorthand: font:[style] weight SIZEpx[/LINE] family
 const fontRe=/(^|;)\s*font\s*:\s*([^;]*?)(\d+(?:\.\d+)?)px(?:\s*\/\s*(\d+(?:\.\d+)?px|[\d.]+))?([^;]*)/g;
 let m;
 while((m=fontRe.exec(body))){const to=sizeOf(m[3]);if(to===null)continue;ratio=to/parseFloat(m[3]);
  let line=m[4]===undefined?'':'/'+(/px$/.test(m[4])?Math.round(parseFloat(m[4])*ratio*100)/100+'px':m[4]);
  decls.push('font:'+m[2]+to+'px'+line+m[5]);}
 const sizeRe=/(^|;)\s*font-size\s*:\s*(\d+(?:\.\d+)?)px/g;
 while((m=sizeRe.exec(body))){const to=sizeOf(m[2]);if(to===null)continue;ratio=to/parseFloat(m[2]);decls.push('font-size:'+to+'px');}
 if(!decls.length)return '';
 const lh=/(^|;)\s*line-height\s*:\s*(\d+(?:\.\d+)?)px/g;
 while((m=lh.exec(body)))decls.push('line-height:'+Math.round(parseFloat(m[2])*ratio*100)/100+'px');
 return decls.join(';');}

function desktopCond(head){// '@media X' -> list of 'min-width:1024px and X' parts, or null when the rule never applies at 1024+
 const cond=head.replace(/^@media\s*/,'').trim();
 const parts=cond.split(/,(?![^()]*\))/).map(s=>s.trim());
 const out=[];
 for(const p of parts){
  if(/max-width\s*:\s*(\d+)px/.test(p)){const w=+p.match(/max-width\s*:\s*(\d+)px/)[1];if(w<1024)continue;}
  if(/prefers-reduced-motion|hover|print|prefers-color|pointer/.test(p))continue;
  const q=p.replace(/^(screen|all)\s+and\s+/,'');out.push(/\(min-width:1024px\)/.test(q)?q:'(min-width:1024px) and '+q);}
 return out.length?out.join(','):null;}

function generate(src){const nodes=parse(src);
 // keyframes and other raw at-rules are not read; only rules and @media are lifted. The document order matters for the
 // cascade, so the rules are kept in the order they were found in.
 const flat=[];
 (function walk(list,ctxCond){for(const n of list){
   if(n.type==='rule'){if(/^@/.test(n.sel)||/^(\d+%|from|to)(\s*,|$)/.test(n.sel))continue;const d=lift(n.body);if(d)flat.push({cond:ctxCond,rule:n.sel.replace(/\s+/g,' ')+'{'+d+';}'});}
   else if(n.type==='at'&&n.head.startsWith('@media')){const c=desktopCond(n.head);if(!c)continue;walk(n.kids,ctxCond?ctxCond+'|'+c:c);}
 }})(nodes,null);
 let body='',cur=undefined;
 for(const f of flat){const cond=f.cond?f.cond.split('|').pop():'(min-width:1024px)';
  if(cond!==cur){if(cur!==undefined)body+='}\n';body+='@media'+(cond.startsWith('(')?'':' ')+cond+'{\n';cur=cond;}
  body+=' '+f.rule+'\n';}
 if(cur!==undefined)body+='}\n';
 return BEGIN+'\n@media(min-width:1024px){:root{'+TOKENS+'}}\n'+body+END+'\n';}

const own=strip(fs.readFileSync(FILE,'utf8'));
// both sheets in load order: ui.css first, then director-review.css without the generated block
const block=generate(strip(fs.readFileSync(BASE,'utf8'))+'\n'+own);
fs.writeFileSync(FILE,own.replace(/\s+$/,'')+'\n'+block);
console.log('desktop type block: '+block.split('\n').length+' lines');
